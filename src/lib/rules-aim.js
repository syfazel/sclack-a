export function countRules(rules = RULES_55) {
  return rules.length
}

export function rulesByChapter(rules = RULES_55) {
  const out = {}
  for (const rule of rules) {
    if (!out[rule.chapter]) out[rule.chapter] = []
    out[rule.chapter].push(rule)
  }
  return out
}

// قوانین یک بخش طرح (۱ تا ۱۳) + قوانین سراسری (۰).
// section 0 یعنی «سراسری» — قوانین سراسری در هر فیلتر بخش هم دیده می‌شوند.
export function rulesForSection(section, rules = RULES_55) {
  if (section === 0) return rules.filter((r) => r.sections.includes(0))
  return rules.filter((r) => r.sections.includes(section) || r.sections.includes(0))
}

export function unmappedRules(rules = RULES_55) {
  return rules.filter((r) => r.unmapped === true)
}
