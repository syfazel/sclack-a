-- فاز ۵ — سند تودرتو: ستون parent_id روی docs
-- پروژه: sclack-a (bbmjurrbkgnysnrtxbnz) — اجرا در Supabase SQL Editor
-- قابل اجرای دوباره: add column با IF NOT EXISTS محافظت شده است.
-- هیچ کلید/رمزی در این فایل نیست؛ هیچ داده‌ای ساخته یا پاک نمی‌شود.
-- هیچ تغییری در سیاست‌های RLS نیست (سیاست‌ها سطری‌اند؛ ستون تازه
-- همان سیاست‌های جدول docs را دارد).
--
-- حذف سندِ والد (اگر روزی از داشبورد یا اسکریپت انجام شود) فرزندها را
-- به ریشه برمی‌گرداند (on delete set null) — در خود اپ حذف سند وجود
-- ندارد (هیچ deleteDocای در کد نیست)، پس این رفتار فعلاً فقط در سطح
-- دیتابیس تعریف شده است.
-- تا وقتی این مهاجرت اجرا نشده، کدِ دیپلوی‌شده با نگهبان ستون ناموجود
-- (docs.js: setDocParent) انتقال را با پیام روشن رد می‌کند و درخت همهٔ
-- سندها را در ریشه نشان می‌دهد؛ هیچ‌چیز دیگری نمی‌شکند.
alter table public.docs add column if not exists parent_id uuid references public.docs(id) on delete set null;

comment on column public.docs.parent_id is
  'والد سند برای تودرتویی (فاز ۵، تصمیم D4)؛ خالی یعنی سند در ریشه است.';
